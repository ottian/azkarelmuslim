/// جزء النهارده في ختمة جزء كل يوم (من 1 لـ 30)
int juzForDay(DateTime start, DateTime day) {
  final a = DateTime.utc(start.year, start.month, start.day);
  final b = DateTime.utc(day.year, day.month, day.day);
  final days = b.difference(a).inDays;
  return (days % 30 + 30) % 30 + 1;
}

